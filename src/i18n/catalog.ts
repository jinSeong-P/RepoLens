export function translate(locale: UiLocale, key: MessageKey, params: MessageParams = {}): string {
  const template = (locale === 'en' ? en : ko)[key] ?? ko[key]
  return typeof template === 'function' ? template(params) : template
}

export function hasMessageKey(value: string): value is MessageKey {
  return Object.hasOwn(ko, value)
}

